static void check_telemetry_not_mistaken_as_ack(void)
{
  uint16_t sequence = 0;
  bool ok;

  /* A valid telemetry packet must never be accepted as an ACK */
  ok = Telemetry_DecodeAck(REF_PACKET_FIX, TELEMETRY_PACKET_SIZE, &sequence);
  if (ok)
  {
    printf("FAIL telemetry_not_ack: telemetry packet was accepted as ACK\n");
    failures++;
  }

  ok = Telemetry_DecodeAck(REF_PACKET_NO_FIX, TELEMETRY_PACKET_SIZE, &sequence);
  if (ok)
  {
    printf("FAIL telemetry_not_ack: no-fix telemetry packet was accepted as ACK\n");
    failures++;
  }
}


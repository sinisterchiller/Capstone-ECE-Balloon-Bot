static unsigned int failures;

/* Reference packet for a valid fix at 48.117300 N, 11.516667 E, 545.4 m, 8 sats. */
/* Generated by the encoder - do not manually calculate. */
static const uint8_t REF_PACKET_FIX[] = {
    0x01,                   /* version = 1 */
    0x01,                   /* type = GPS_STATUS */
    0x2A, 0x00,             /* sequence = 42 (little-endian) */
    0x01,                   /* fix_valid = 1 */
    0x34, 0x36, 0xDE, 0x02, /* latitude = 48117300 (little-endian) */
    0xFB, 0xBA, 0xAF, 0x00, /* longitude = 11516667 (little-endian) */
    0x0C, 0xD5, 0x00, 0x00, /* altitude = 54540 cm (little-endian) */
    0x08                    /* satellites = 8 */
};
_Static_assert(sizeof(REF_PACKET_FIX) == TELEMETRY_PACKET_SIZE, "REF_PACKET_FIX size mismatch");

static const uint8_t REF_PACKET_NO_FIX[] = {
    0x01,                   /* version = 1 */
    0x01,                   /* type = GPS_STATUS */
    0x2B, 0x00,             /* sequence = 43 */
    0x00,                   /* fix_valid = 0 */
    0x00, 0x00, 0x00, 0x00, /* latitude = 0 */
    0x00, 0x00, 0x00, 0x00, /* longitude = 0 */
    0x00, 0x00, 0x00, 0x00, /* altitude = 0 */
    0x00                    /* satellites = 0 */
};
_Static_assert(sizeof(REF_PACKET_NO_FIX) == TELEMETRY_PACKET_SIZE, "REF_PACKET_NO_FIX size mismatch");

/* Reference ACK packet for sequence 42 (little-endian). */
static const uint8_t REF_ACK_PACKET[] = {
    0x01,                   /* version = 1 */
    0x02,                   /* type = ACK */
    0x2A, 0x00              /* sequence = 42 (little-endian) */
};
_Static_assert(sizeof(REF_ACK_PACKET) == TELEMETRY_ACK_PACKET_SIZE, "REF_ACK_PACKET size mismatch");

static void check_encode_fix(void)
{
  TelemetryGpsStatus status = {0};
  uint8_t buffer[TELEMETRY_PACKET_SIZE];
  bool ok;

  status.fix_valid = 1;
  status.latitude_udeg = 48117300;
  status.longitude_udeg = 11516667;
  status.altitude_cm = 54540;
  status.satellites_used = 8;
  status.fix_timestamp_ms = 12345;
  status.fix_sequence = 1;

  ok = Telemetry_EncodeGpsStatus(&status, 42, buffer, sizeof(buffer));
  if (!ok)
  {
    printf("FAIL encode_fix: Telemetry_EncodeGpsStatus returned false\n");
    failures++;
    return;
  }
  if (memcmp(buffer, REF_PACKET_FIX, TELEMETRY_PACKET_SIZE) != 0)
  {
    printf("FAIL encode_fix: packet mismatch\n");
    for (uint16_t i = 0; i < TELEMETRY_PACKET_SIZE; i++)
    {
      if (buffer[i] != REF_PACKET_FIX[i])
      {
        printf("  byte %u: got 0x%02X, expected 0x%02X\n", i, buffer[i], REF_PACKET_FIX[i]);
      }
    }
    failures++;
    return;
  }
}


static void check_decode_fix(void)
{
  TelemetryGpsStatus status = {0};
  uint16_t sequence = 0;
  bool ok;

  ok = Telemetry_DecodeGpsStatus(REF_PACKET_FIX, sizeof(REF_PACKET_FIX), &status, &sequence);
  if (!ok)
  {
    printf("FAIL decode_fix: Telemetry_DecodeGpsStatus returned false\n");
    failures++;
    return;
  }
  if (sequence != 42)
  {
    printf("FAIL decode_fix: sequence %u, expected 42\n", sequence);
    failures++;
  }
  if (status.fix_valid != 1)
  {
    printf("FAIL decode_fix: fix_valid %u, expected 1\n", status.fix_valid);
    failures++;
  }
  if (status.latitude_udeg != 48117300)
  {
    printf("FAIL decode_fix: latitude %d, expected 48117300\n", status.latitude_udeg);
    failures++;
  }
  if (status.longitude_udeg != 11516667)
  {
    printf("FAIL decode_fix: longitude %d, expected 11516667\n", status.longitude_udeg);
    failures++;
  }
  if (status.altitude_cm != 54540)
  {
    printf("FAIL decode_fix: altitude %d, expected 54540\n", status.altitude_cm);
    failures++;
  }
  if (status.satellites_used != 8)
  {
    printf("FAIL decode_fix: satellites %u, expected 8\n", status.satellites_used);
    failures++;
  }
}

